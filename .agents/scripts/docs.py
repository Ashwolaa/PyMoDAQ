#!/usr/bin/env python3
"""Generate .agents/COMMANDS.md: every command, agent, script and runner, from the files themselves. Usage:

  docs.py [--write]      print the page (--write: also write .agents/COMMANDS.md)
  docs.py --check        exit 1 if the committed page differs from what the files say (the tests call this)
Sources: the frontmatter of `.claude/commands/*.md` (description, argument-hint) and `.claude/agents/*.md` (name,
model, tools, description), the first docstring line of `.agents/scripts/*.py` and `.agents/runner/*`, and
`.claude/settings.json` hooks. Edit those files, never COMMANDS.md.
"""
import argparse
import ast
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _common import AGENTS_DIR

REPO = AGENTS_DIR.parent
OUT = AGENTS_DIR / "COMMANDS.md"


def frontmatter(path: Path) -> dict:
    m = re.match(r"^---\n(.*?)\n---\n", path.read_text(), re.S)
    out = {}
    for line in (m.group(1).splitlines() if m else []):
        k, _, v = line.partition(":")
        out[k.strip()] = v.strip().strip('"')
    return out


def first_doc_line(path: Path) -> str:
    text = path.read_text()
    if path.suffix == ".py":
        try:
            doc = ast.get_docstring(ast.parse(text)) or ""
        except SyntaxError:
            doc = ""
    else:  # shell: the first comment block after the shebang
        doc = "\n".join(l.lstrip("# ") for l in text.splitlines()[1:6] if l.startswith("#"))
    first = " ".join(doc.strip().split("\n\n")[0].split())
    first = re.split(r"\s*Usage\b", first)[0].rstrip(" .:")  # drop the usage block that often follows
    m = re.match(r"(.{20,}?(?<!e\.g)(?<!i\.e)[.!?])(\s|$)", first)  # first sentence ("e.g." is not an end)
    return (m.group(1) if m else first)[:200]


def cell(s: str) -> str:
    return s.replace("|", "\\|")


def render() -> str:
    L = ["# Commands, agents and scripts", "",
         "Generated by `python3 .agents/scripts/docs.py --write` from the files themselves (also run by "
         "`status.py --write`). Do not edit: change the command, agent or script instead. Start here: `.agents/README.md`.", "",
         "## Commands (`/optimize-*`, in `.claude/commands/`)", "", "| command | arguments | what it does |", "|---|---|---|"]
    for p in sorted((REPO / ".claude/commands").glob("*.md")):
        f = frontmatter(p)
        L.append(f"| `/{p.stem}` | {cell(f.get('argument-hint', '') or '-')} | {cell(f.get('description', ''))} |")
    L += ["", "## Agents (`.claude/agents/`)", "", "| agent | model | tools | role |", "|---|---|---|---|"]
    for p in sorted((REPO / ".claude/agents").glob("*.md")):
        f = frontmatter(p)
        L.append(f"| `{f.get('name', p.stem)}` | {f.get('model', '?')} | {cell(f.get('tools', ''))} | {cell(f.get('description', ''))} |")
    L += ["", "## Scripts (`.agents/scripts/`, run with `python3` after `[tools].env`)", "", "| script | what it does |", "|---|---|"]
    for p in sorted((AGENTS_DIR / "scripts").glob("*")):
        if p.is_file() and p.suffix in (".py", ".sh") and not p.name.startswith("_"):
            L.append(f"| `{p.name}` | {cell(first_doc_line(p))} |")
    lib = AGENTS_DIR / "scripts" / "agentlib"
    L += ["", "Shared library `agentlib/`: " + "; ".join(
        f"`{p.stem}` {first_doc_line(p).rstrip('.')}" for p in sorted(lib.glob("*.py")) if p.stem != "__init__") + "."]
    L += ["", "## Runner (`.agents/runner/`)", "", "| file | what it does |", "|---|---|"]
    for p in sorted((AGENTS_DIR / "runner").glob("*")):
        if p.is_file() and p.suffix in (".py", ".sh"):
            L.append(f"| `{p.name}` | {cell(first_doc_line(p))} |")
    settings = REPO / ".claude/settings.json"
    if settings.exists():
        L += ["", "## Hooks (`.claude/settings.json`)", ""]
        for event, entries in json.loads(settings.read_text()).get("hooks", {}).items():
            for e in entries:
                for h in e.get("hooks", []):
                    script = re.search(r"\.claude/hooks/(\S+?)\"?$", h.get("command", ""))
                    desc = first_doc_line(REPO / ".claude/hooks" / script.group(1)) if script else h.get("command", "")
                    L.append(f"- {event} on `{e.get('matcher', '*')}`: {desc}")
    return "\n".join(L) + "\n"


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--write", action="store_true")
    p.add_argument("--check", action="store_true")
    a = p.parse_args()
    text = render()
    if a.check:
        if not OUT.exists() or OUT.read_text() != text:
            print("COMMANDS.md is out of date: run python3 .agents/scripts/docs.py --write")
            sys.exit(1)
        print("COMMANDS.md is up to date")
        return
    if a.write:
        OUT.write_text(text)
    print(text, end="")


if __name__ == "__main__":
    main()
